"""Builds lib/twelve-data.mjs: the 100 rule-checked 12-lead ECGs (two sets of 50).

    pip install numpy
    python3 tools/generator/build_twelve.py

The 12-lead data is served by the API (GET /api/areas/twelve), not as a public file,
so it stays closed to students until the instructor opens it from the scoreboard.
"""
import json, os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np
import twelve as T

OUT = os.path.normpath(os.path.join(HERE, "..", "..", "lib", "twelve-data.mjs"))


def encode(y):
    v = np.round(np.clip(y[::2], -3, 3) * 100).astype(int)  # 500 Hz, 0.01 mV
    out, prev = [], None
    for x in v:
        if prev is None or abs(x - prev) > 40:
            out.append(f"|{x}|")
        else:
            out.append(chr(int(x - prev) + 80))
        prev = x
    return "".join(out)


def main():
    # Set 1 (ECGs 1-50) keeps its original seed and order so students' earlier answers stay valid.
    set1 = T.generate()
    set2 = T.generate(seed=20261201, plan=T.PLAN2)
    order1 = list(range(len(set1))); random.Random("twelve-order").shuffle(order1)
    order2 = list(range(len(set2))); random.Random("twelve-order-2").shuffle(order2)
    ordered = [set1[i] for i in order1] + [set2[i] for i in order2]
    cats = list(dict.fromkeys(it["cat"] for it in set1 + set2))
    rng = random.Random("twelve-options")
    seen, out = set(), []
    for n, it in enumerate(ordered, 1):
        e = it["ecg"]
        leads = {}
        for ld in T.LEADS:
            a, b = int(T.COL_OF[ld] * T.WIN * T.FS), int((T.COL_OF[ld] + 1) * T.WIN * T.FS)
            leads[ld] = encode(e.noisy[ld][a:b])
        leads["rhythm"] = encode(e.noisy["II"])
        assert leads["rhythm"] not in seen, "duplicate ECG"
        seen.add(leads["rhythm"])
        near = [c for c in T.related_to(it["cat"]) if c in cats]
        pool = near if len(near) >= 3 else [c for c in cats if c != it["cat"]]
        opts = rng.sample(pool, 3) + [it["cat"]]; rng.shuffle(opts)
        out.append({"n": n, "cat": it["cat"], "name": it["name"], "rows": it["rows"], "action": it["action"], "options": opts,
                    "hints": T.hints_for(it), "leads": leads})
    assert len(out) == 100 and len(seen) == 100
    doc = {"key": "twelve", "title": "12-lead ECGs", "categories": cats,
           "cats": {k: {"group": "twelve", "key": v[0], "clue": v[1]} for k, v in T.CATS.items()}, "items": out}
    with open(OUT, "w") as f:
        f.write("// Generated by tools/generator/build_twelve.py. Do not edit by hand.\n")
        f.write("// 100 rule-checked 12-lead ECGs, served only when the instructor opens the 12-lead area.\n")
        f.write("export default " + json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{len(out)} ECGs, {len(cats)} findings, {os.path.getsize(OUT) // 1024} KB -> {OUT}")


if __name__ == "__main__":
    main()
