"""Builds lib/twelve-data.mjs: the 150 rule-checked 12-lead ECGs (three sets of 50; set 3 looks like a real patient in the field).

    pip install numpy
    python3 tools/generator/build_twelve.py

The 12-lead data is served by the API (GET /api/areas/twelve), not as a public file,
so it stays closed to students until the instructor opens it from the scoreboard.
"""
import json, os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np
import twelve as T
import twelve_marks as TM   # what proves each finding, for the on-ECG teaching marks
import twelve_field as TF   # real-patient look for set 3

OUT = os.path.normpath(os.path.join(HERE, "..", "..", "lib", "twelve-data.mjs"))


def encode(y):
    v = np.round(np.clip(y[::2], -3, 3) * 100).astype(int)  # 500 Hz, 0.01 mV
    out, prev = [], None
    for x in v:
        if prev is None or abs(x - prev) > 40:
            out.append(f"|{x}|")
        else:
            out.append(chr(int(x - prev) + 80))
        prev = x
    return "".join(out)


PLAN3 = [(T.f_normal, 4), (T.f_inferior, 4), (T.f_anterior, 3), (T.f_lateral, 3), (T.f_posterior, 3), (T.f_rbbb, 2), (T.f_lbbb, 2),
         (T.f_hyperk, 3), (T.f_pericarditis, 2), (T.f_anterolateral, 3), (T.f_wellens, 3), (T.f_dewinter, 2), (T.f_avr, 3), (T.f_lvh, 2),
         (T.f_early_repol, 3), (T.f_hypok, 2), (T.f_brugada, 2), (T.f_wpw, 2), (T.f_longqt, 2)]


def main():
    # Set 1 (ECGs 1-50) keeps its original seed and order so students' earlier answers stay valid.
    set1 = T.generate()
    set2 = T.generate(seed=20261201, plan=T.PLAN2)
    # Set 3 (ECGs 101-150): every finding again, on ECGs that look like a real patient in the field.
    TF.install()
    set3 = T.generate(seed=20261205, plan=PLAN3)
    TF.uninstall()
    for it in set3:
        it["field"] = True
    order1 = list(range(len(set1))); random.Random("twelve-order").shuffle(order1)
    order2 = list(range(len(set2))); random.Random("twelve-order-2").shuffle(order2)
    order3 = list(range(len(set3))); random.Random("twelve-order-3").shuffle(order3)
    ordered = [set1[i] for i in order1] + [set2[i] for i in order2] + [set3[i] for i in order3]
    cats = list(dict.fromkeys(it["cat"] for it in set1 + set2 + set3))
    rng = random.Random("twelve-options")
    seen, out = set(), []
    for n, it in enumerate(ordered, 1):
        e = it["ecg"]
        leads = {}
        for ld in T.LEADS:
            a, b = int(T.COL_OF[ld] * T.WIN * T.FS), int((T.COL_OF[ld] + 1) * T.WIN * T.FS)
            leads[ld] = encode(e.noisy[ld][a:b])
        leads["rhythm"] = encode(e.noisy["II"])
        assert leads["rhythm"] not in seen, "duplicate ECG"
        seen.add(leads["rhythm"])
        near = [c for c in T.related_to(it["cat"]) if c in cats]
        pool = near if len(near) >= 3 else [c for c in cats if c != it["cat"]]
        opts = rng.sample(pool, 3) + [it["cat"]]; rng.shuffle(opts)
        row = {"n": n, "cat": it["cat"], "name": it["name"], "rows": it["rows"], "action": it["action"], "options": opts,
               "hints": T.hints_for(it), "leads": leads, "mk": TM.marks(it["cat"], e)}
        if it.get("field"):
            row["field"] = 1
        out.append(row)
    assert len(out) == 150 and len(seen) == 150
    doc = {"key": "twelve", "title": "12-lead ECGs", "categories": cats,
           "cats": {k: {"group": "twelve", "key": v[0], "clue": v[1]} for k, v in T.CATS.items()}, "items": out}
    with open(OUT, "w") as f:
        f.write("// Generated by tools/generator/build_twelve.py. Do not edit by hand.\n")
        f.write("// 150 rule-checked 12-lead ECGs, served only when the instructor opens the 12-lead area.\n")
        f.write("export default " + json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{len(out)} ECGs, {len(cats)} findings, {os.path.getsize(OUT) // 1024} KB -> {OUT}")


if __name__ == "__main__":
    main()
